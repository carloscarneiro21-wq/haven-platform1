# 🏁 Run Result
# ============================================================

class RunResult(BaseModel):
    """
    Complete result from GrowthOrchestrator.run().
    
    Contains all pipeline step results.
    """
    # Identity (idempotent)
    run_id: str
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    
    # Mode & Status
    mode: RunMode
    status: RunStatus
    is_replay: bool = False
    
    # Context
    symbol: str
    venue: str
    
    # Router decision
    regime: str = ""
    confidence: str = ""
    recommended_agent: str = ""
    recommended_preset_id: str = ""
    
    # Pipeline results
    guardian_result: Optional[GuardianResult] = None
    viability_result: Optional[ViabilityResult] = None
    intent_plans: List[IntentPlan] = []
    execution_result: Optional[ExecutionResult] = None
    
    # Summary
    orders_created: int = 0
    orders_filled: int = 0
    pnl_delta_eur: float = 0.0
    
    # Reasons
    reason_codes: List[str] = []
    block_reason: Optional[str] = None
    
    # Raw data (for debugging)
    snapshot: Optional[MarketSnapshot] = None
    
    @staticmethod
    def generate_run_id(
        timestamp_bucket: str,
        config_hash: str,
        market_hash: str,
    ) -> str:
        """
        Generate deterministic run_id for idempotency.
        
        run_id = hash(timestamp_bucket + config_hash + market_hash)
        """
        data = f"{timestamp_bucket}:{config_hash}:{market_hash}"
        return hashlib.sha256(data.encode()).hexdigest()[:24]


