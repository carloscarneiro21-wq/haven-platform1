"""
Growth Module Interfaces
========================

Clean contracts for all Growth Module components.

Interfaces:
- GrowthOrchestrator.run(mode) -> RunResult
- GrowthModule.evaluate(snapshot) -> IntentPlan[]
- ViabilityEngine.assess(intent, snapshot) -> ViabilityResult
- Guardian.approve(context) -> GuardianResult
- PaperExecutor.execute(intent) -> ExecutionResult

Run Modes:
- DryRun: No execution, no positions
- RunOnce: Full execution with positions
- Replay: Load existing run (idempotent)

Idempotency:
- run_id = hash(timestamp_bucket + config_hash + market_hash)
- If run_id exists → Replay mode
- Never re-executes positions
"""

from abc import ABC, abstractmethod
from datetime import datetime, timezone
from typing import Dict, Any, Optional, List
from pydantic import BaseModel, Field
from enum import Enum
import hashlib
import json


# ============================================================
# 🔁 Run Modes
# ============================================================

class RunMode(str, Enum):
    """
    Run modes for Growth Module execution.
    
    | Mode    | Execution | Positions |
    |---------|-----------|-----------|
    | DRY_RUN | ❌        | ❌        |
    | RUN_ONCE| ✅        | ✅        |
    | REPLAY  | ❌        | ❌        |
    """
    DRY_RUN = "dry_run"    # No execution, no positions
    RUN_ONCE = "run_once"  # Full execution with positions
    REPLAY = "replay"      # Load existing run (idempotent)


class RunStatus(str, Enum):
    """Status of a run execution."""
    SUCCESS = "success"
    BLOCKED = "blocked"
    PAUSED = "paused"
    ERROR = "error"
    REPLAYED = "replayed"


# ============================================================
# 📸 Market Snapshot
# ============================================================

class MarketSnapshot(BaseModel):
    """Point-in-time market data snapshot."""
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    symbol: str
    venue: str
    
    # Price data
    last_price: float
    bid: float
    ask: float
    spread_pct: float
    
    # Volatility
    atr_pct: float
    atr_14: float
    
    # Trend
    adx: float
    ma_slope_pct: float
    trend_direction: int  # -1, 0, 1
    
    # Volume
    volume_24h: float
    volume_ratio: float
    
    # Data quality
    data_age_seconds: float
    data_quality: float
    
    def get_hash(self) -> str:
        """Generate deterministic hash of market data."""
        # Round values to avoid floating point issues
        data = {
            "symbol": self.symbol,
            "venue": self.venue,
            "price": round(self.last_price, 2),
            "spread": round(self.spread_pct, 4),
            "atr": round(self.atr_pct, 4),
            "adx": round(self.adx, 1),
            "trend": self.trend_direction,
        }
        return hashlib.sha256(json.dumps(data, sort_keys=True).encode()).hexdigest()[:16]


