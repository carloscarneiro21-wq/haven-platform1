# 🧩 Interface Definitions (Abstract Base Classes)
# ============================================================

class IGrowthOrchestrator(ABC):
    """
    Main orchestrator interface.
    
    run(mode: RunMode) -> RunResult
    """
    
    @abstractmethod
    async def run(self, mode: RunMode, symbol: str = "BTC/USDT") -> RunResult:
        """
        Execute a Growth Module run.
        
        Args:
            mode: DRY_RUN, RUN_ONCE, or REPLAY
            symbol: Trading pair
            
        Returns:
            RunResult with complete pipeline results
            
        Idempotency:
            - run_id is deterministic
            - If run_id exists, returns replay
            - Never re-executes positions
        """
        pass
    
    @abstractmethod
    async def get_run(self, run_id: str) -> Optional[RunResult]:
        """Get a run by ID (for replay)."""
        pass


class IGrowthModule(ABC):
    """
    Growth Module evaluation interface.
    
    evaluate(snapshot) -> IntentPlan[]
    """
    
    @abstractmethod
    async def evaluate(self, snapshot: MarketSnapshot) -> List[IntentPlan]:
        """
        Evaluate market snapshot and generate intent plans.
        
        Args:
            snapshot: Point-in-time market data
            
        Returns:
            List of IntentPlan (may be empty if PAUSE recommended)
        """
        pass


class IViabilityEngine(ABC):
    """
    Viability assessment interface.
    
    assess(intent, snapshot) -> ViabilityResult
    """
    
    @abstractmethod
    async def assess(
        self,
        intent: IntentPlan,
        snapshot: MarketSnapshot,
    ) -> ViabilityResult:
        """
        Assess viability of an intent plan.
        
        Args:
            intent: The trading intent plan
            snapshot: Current market data
            
        Returns:
            ViabilityResult with cost analysis
        """
        pass


class IGuardian(ABC):
    """
    Guardian approval interface.
    
    approve(context) -> GuardianResult
    """
    
    @abstractmethod
    async def approve(self, context: GuardianContext) -> GuardianResult:
        """
        Check if trade is allowed by risk rules.
        
        Args:
            context: Trade context with risk parameters
            
        Returns:
            GuardianResult with allow/block decision
        """
        pass


class IPaperExecutor(ABC):
    """
    Paper execution interface.
    
    execute(intent) -> ExecutionResult
    """
    
    @abstractmethod
    async def execute(self, intent: IntentPlan) -> ExecutionResult:
        """
        Execute intent plan in paper trading mode.
        
        Args:
            intent: The trading intent plan
            
        Returns:
            ExecutionResult with order/fill details
        """
        pass


