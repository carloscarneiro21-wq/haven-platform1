# 🧷 Idempotency Helpers
# ============================================================

def get_timestamp_bucket(granularity_minutes: int = 5) -> str:
    """
    Get timestamp bucket for idempotency.
    
    Rounds timestamp to nearest bucket (default 5 min).
    """
    now = datetime.now(timezone.utc)
    bucket_minutes = (now.minute // granularity_minutes) * granularity_minutes
    bucket_time = now.replace(minute=bucket_minutes, second=0, microsecond=0)
    return bucket_time.strftime("%Y%m%d%H%M")


def get_config_hash(config: Dict[str, Any]) -> str:
    """Generate hash of configuration."""
    return hashlib.sha256(
        json.dumps(config, sort_keys=True, default=str).encode()
    ).hexdigest()[:16]
